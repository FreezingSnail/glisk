#!/bin/sh
# Generate a deterministic multi-thousand-line report for the release memory
# check. It stays well inside Glisk's 4 MiB input and DOM budgets.
#   scripts/make-long-report.sh [output] [sections]
set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
out=${1:-"$root/dist/long-report.html"}
sections=${2:-320}

mkdir -p "$(dirname -- "$out")"

{
	cat <<'EOF'
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Glisk long report fixture</title>
<style>
  :root { color-scheme: dark; --bg:#0f1419; --card:#1b2430; --line:#3b4d60;
          --ink:#e8eef5; --muted:#a9b8c8; --accent:#71d6a8; --accent-2:#f0c674; }
  * { box-sizing: border-box; }
  html { background: var(--bg); color: var(--ink); }
  body { margin:0; padding:24px 20px 40px; background:var(--bg); color:var(--ink);
         font-family:"Helvetica Neue",Helvetica,Arial,sans-serif; font-size:16px; line-height:1.45; }
  main { max-width:980px; margin:0 auto; }
  h1 { font-size:30px; margin:0 0 8px; }
  h2 { font-size:21px; margin:0 0 8px; }
  p { margin:0 0 10px; color:var(--muted); }
  nav a { color:var(--accent); margin-right:16px; }
  .cards { display:flex; flex-wrap:wrap; gap:12px; margin:0 0 16px; }
  .card { flex:1 1 260px; min-width:0; background:var(--card);
          border:1px solid var(--line); border-radius:12px; padding:14px 15px; }
  .card p { margin:0; font-size:14px; }
  details { background:var(--card); border:1px solid var(--line); border-radius:12px;
            padding:0 14px 2px; margin:0 0 16px; }
  summary { cursor:pointer; padding:11px 0; color:var(--accent-2); font-weight:700; }
  section { margin:0 0 30px; }
  a { color:var(--accent); }
  a:focus, summary:focus { outline:3px solid var(--accent-2); outline-offset:2px; }
</style>
</head>
<body>
<main>
<h1>Glisk long report fixture</h1>
<p>Generated by scripts/make-long-report.sh. Scroll from the top to the end while raster memory stays viewport-sized.</p>
<nav aria-label="Jump"><a href="#end">End of report</a><a href="#section-1">First section</a></nav>
EOF
	i=1
	while [ "$i" -le "$sections" ]; do
		printf '<section id="section-%s"><h2>Section %s: evidence log</h2>' "$i" "$i"
		printf '<div class="cards"><div class="card"><p>Card %s keeps flexible width in narrow windows.</p></div>' "$i"
		printf '<div class="card"><p>Viewport frames replace one image; the document grows, the raster does not.</p></div></div>'
		printf '<p>Paragraph %s records bounded ingestion, offline resources, and a stable reading position.</p>' "$i"
		printf '<p>Second paragraph %s adds enough flow to make this report much longer than the reference example.</p>' "$i"
		if [ $((i % 5)) -eq 0 ]; then
			printf '<details id="note-%s"><summary>Evidence note %s</summary><p>Closed disclosure body %s remains searchable and plain-text extractable.</p></details>' "$i" "$i" "$i"
		fi
		printf '</section>\n'
		i=$((i + 1))
	done
	cat <<'EOF'
<section id="end"><h2>End of report</h2><p>You reached the final section. Quitting restores the shell and deletes the active image.</p></section>
</main>
</body>
</html>
EOF
} >"$out"

printf 'glisk: wrote %s section(s) to %s (%s bytes)\n' "$sections" "$out" "$(wc -c <"$out" | tr -d ' ')"
